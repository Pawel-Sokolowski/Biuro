"""Durable reminder attempts, shared by every running workstation."""


def apply(conn):
    conn.execute("""CREATE TABLE IF NOT EXISTS email_reminder_log (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        kind TEXT NOT NULL,
        target TEXT NOT NULL,
        scheduled_date DATE NOT NULL,
        recipient TEXT NOT NULL,
        subject TEXT NOT NULL,
        body TEXT NOT NULL,
        status TEXT NOT NULL DEFAULT 'sending' CHECK (status IN ('sending', 'sent', 'failed')),
        error TEXT,
        created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        sent_at TIMESTAMPTZ,
        UNIQUE(kind, target, scheduled_date)
    )""")
    conn.execute("""INSERT INTO app_settings(klucz, wartosc) VALUES ('schema_hash', '2026-11-09.1')
        ON CONFLICT(klucz) DO UPDATE SET wartosc = EXCLUDED.wartosc""")
