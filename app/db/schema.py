SCHEMA_LOCK_ID = 748201
SCHEMA_KEY = "schema_hash"
# Podnieś przy każdej zmianie schematu (nowe tabele/kolumny/migracje) - wymusza migrację.
SCHEMA_VERSION = "2026-10-22.1"


def _schema_hash() -> str:
    return SCHEMA_VERSION


def schema_is_current() -> bool:
    """Szybki, nieblokujący odczyt: czy baza była zmigrowana tą wersją schema.py."""
    conn = get_conn()
    try:
        cur = conn.cursor()
        cur.execute("SELECT to_regclass('app_settings') IS NOT NULL")
        if not cur.fetchone()[0]:
            return False
        cur.execute("SELECT wartosc FROM app_settings WHERE klucz = %s", (SCHEMA_KEY,))
        row = cur.fetchone()
        return bool(row) and row[0] == _schema_hash()
    finally:
        conn.rollback()
        conn.close()


def _safe_alter_add_column(cur: psycopg.Cursor, table: str, column_def: str):
    """Dodaje kolumnę, jeśli jej jeszcze nie ma. Przykład: "systemowe INTEGER NOT NULL DEFAULT 0".

    Najpierw sprawdza katalog, bo samo ALTER ... IF NOT EXISTS blokuje tabelę
    (także gdy kolumna istnieje) i potrafi zawiesić start przy otwartych transakcjach.
    """
    column = column_def.split()[0]
    cur.execute(
        "SELECT 1 FROM information_schema.columns "
        "WHERE table_schema = current_schema() AND table_name = %s AND column_name = %s",
        (table, column),
    )
    if cur.fetchone():
        return
    cur.execute(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {column_def};")


def _ensure_index(cur: psycopg.Cursor, name: str, table: str, columns: str):
    cur.execute("SELECT 1 FROM pg_indexes WHERE schemaname = current_schema() AND indexname = %s", (name,))
    if not cur.fetchone():
        cur.execute(f"CREATE INDEX IF NOT EXISTS {name} ON {table}({columns})")


