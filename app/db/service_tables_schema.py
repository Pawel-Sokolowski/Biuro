"""DDL współdzielone przez migrację historii wysyłki oraz bootstrap testów."""

BULK_MAIL_TABLES = (
    '''
    CREATE TABLE IF NOT EXISTS bulk_mail_runs (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        actor_id INTEGER,
        account_id INTEGER,
        sender TEXT,
        subject TEXT NOT NULL DEFAULT '',
        body TEXT NOT NULL DEFAULT '',
        attachments TEXT NOT NULL DEFAULT '[]',
        recipients_total INTEGER NOT NULL DEFAULT 0,
        started_at TEXT NOT NULL,
        finished_at TEXT,
        remaining INTEGER,
        stopped INTEGER NOT NULL DEFAULT 0
    )''',
    '''
    CREATE TABLE IF NOT EXISTS bulk_mail_batches (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        run_id INTEGER NOT NULL REFERENCES bulk_mail_runs(id) ON DELETE CASCADE,
        recipients TEXT NOT NULL,
        status TEXT NOT NULL,
        info TEXT,
        created_at TEXT NOT NULL
    )''',
    'CREATE INDEX IF NOT EXISTS idx_bulk_mail_batches_run ON bulk_mail_batches(run_id)',
)

CHECKING_QUEUE_TABLES = (
    '''
    CREATE TABLE IF NOT EXISTS checking_requests (
        id TEXT PRIMARY KEY,
        actor_id INTEGER NOT NULL,
        kind TEXT NOT NULL,
        company_ids TEXT NOT NULL,
        period TEXT NOT NULL,
        state TEXT NOT NULL,
        attempts INTEGER NOT NULL DEFAULT 0,
        created_at TEXT NOT NULL,
        started_at TEXT,
        finished_at TEXT,
        error TEXT,
        results TEXT
    )''',
    'CREATE INDEX IF NOT EXISTS idx_checking_requests_state ON checking_requests(state, created_at)',
    'CREATE INDEX IF NOT EXISTS idx_checking_requests_actor ON checking_requests(actor_id, created_at DESC)',
)


def apply_bulk_mail(conn):
    for statement in BULK_MAIL_TABLES:
        conn.execute(statement)


def apply_checking_queue(conn):
    for statement in CHECKING_QUEUE_TABLES:
        conn.execute(statement)


def apply(conn):
    apply_bulk_mail(conn)
    apply_checking_queue(conn)
